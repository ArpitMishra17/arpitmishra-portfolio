// Traces logos with ascii.rest's kit — the same "logo" style its library
// logos are drawn in — and writes them as Go for logos_traced.go.
//
//   node trace.mjs <ascii.rest>/src/kit/image.ts <cols> <rows> "Name=file.rgba:WxH" ...
import { readFileSync } from "node:fs";

const [kit, cols, rows, ...items] = process.argv.slice(2);
const { drawing, imagePalette } = await import(kit);
const q = (s) => JSON.stringify(s);
let go = `// Code generated by tools/logos/gen.sh — DO NOT EDIT.
// Traced with ascii.rest's kit (github.com/bas3line/ascii, MIT) from devicon
// and Simple Icons artwork. Logos are trademarks of their owners, shown to
// name the technology.

package main

var tracedLogos = []logoData{
`;
for (const item of items) {
  const [, name, file, w, h] = /^(.+?)=(.+):(\d+)x(\d+)$/.exec(item);
  const d = drawing(new Uint8Array(readFileSync(file)), +w, +h, { style: "logo", width: +cols, height: +rows });
  const pal = imagePalette(d);
  go += `\t{name: ${q(name)}, cols: ${d.cols}, rows: ${d.rows}, small: true,\n`;
  go += `\t\tpalette: []string{${[...pal.light, ...pal.dark].map(q).join(", ")}},\n`;
  go += `\t\tart: []string{\n${d.art.map((l) => `\t\t\t${q(l)},`).join("\n")}\n\t\t},\n`;
  go += `\t\tink: []string{\n${d.ink.map((l) => `\t\t\t${q(l)},`).join("\n")}\n\t\t}},\n`;
}
process.stdout.write(go + "}\n");
